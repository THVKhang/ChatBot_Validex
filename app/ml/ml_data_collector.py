def save_training_record(
    features: dict[str, Any],
    labels: dict[str, Any],
    metadata: dict[str, Any] | None = None,
    output_path: str = DEFAULT_TRAINING_DATA_PATH,
) -> None:
    """Append a single training record (features + labels) to the JSONL file.

    Parameters
    ----------
    features : dict
        The extracted feature vector.
    labels : dict
        The quality labels (faithfulness, relevance, quality_class).
    metadata : dict, optional
        Additional metadata (topic, timestamp, etc.).
    output_path : str
        Path to the JSONL file.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    record = {
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "features": features,
        "labels": labels,
        "metadata": metadata or {},
    }

    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(record, ensure_ascii=False) + "\n")

    logger.info(
        "ML Data Collector: saved training record (quality=%s, source=%s) → %s",
        labels.get("quality_class", "?"),
        labels.get("label_source", "?"),
        output_path,
    )


def collect_from_state(
    state: dict[str, Any],
    use_llm_judge: bool = False,
    output_path: str = DEFAULT_TRAINING_DATA_PATH,
) -> dict[str, Any]:
    """Full collection pipeline: extract features → generate labels → save.

    Parameters
    ----------
    state : dict
        The final GraphState after a complete RAG pipeline run.
    use_llm_judge : bool
        If True, attempt LLM-as-judge labeling first (costs API tokens).
        Falls back to heuristic labels on failure.
    output_path : str
        Path to persist the training record.

    Returns
    -------
    dict
        The extracted features (also stored in state as ml_features).
    """
    features = extract_features(state)

    # Generate labels
    labels = None
    if use_llm_judge:
        labels = generate_labels_llm_judge(state)

    if labels is None:
        labels = generate_labels_heuristic(state, features)

    # Metadata for traceability
    parsed = state.get("parsed", {})
    metadata = {
        "topic": parsed.get("topic", ""),
        "intent": parsed.get("intent", ""),
        "complexity_level": state.get("complexity_level", "simple"),
        "request_id": state.get("request_id", ""),
    }

    save_training_record(features, labels, metadata, output_path)

    return {
        "ml_features": features,
        "ml_labels": labels,
    }


def count_training_records(path: str = DEFAULT_TRAINING_DATA_PATH) -> int:
    """Count the number of training records in the JSONL file."""
    p = Path(path)
    if not p.exists():
        return 0
    count = 0
    for line in p.read_text(encoding="utf-8").splitlines():
        if line.strip():
            count += 1
    return count


