"""ML Training Data Collector — Harvests feature vectors and quality labels
from each RAG Multi-Agent pipeline run.

After every blog generation cycle, this module extracts a structured feature
vector from the GraphState and persists it (with quality labels) into a JSONL
file that can later be consumed by the ML Trainer (ml_trainer.py).

Features are computed entirely from data already available in the pipeline
(zero additional API calls).  Labels are initially generated by an
LLM-as-a-judge approach; once enough data is collected the trained ML model
replaces the LLM judge.
"""

from __future__ import annotations

import json
import logging
import os
import re
import time
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

# Default storage path for training data
DEFAULT_TRAINING_DATA_PATH = "data/ml/training_data.jsonl"


# ---------------------------------------------------------------------------
# Feature Extraction
# ---------------------------------------------------------------------------

def _count_headings(draft: str) -> int:
    """Count markdown H2 headings in a draft."""
    return len(re.findall(r"^## ", draft, re.MULTILINE))


def _keyword_density(draft: str, topic: str) -> float:
    """Compute topic keyword density (0.0 – 1.0 scale)."""
    if not draft or not topic:
        return 0.0
    topic_words = set(re.findall(r"\w+", topic.lower()))
    draft_words = re.findall(r"\w+", draft.lower())
    if not draft_words or not topic_words:
        return 0.0
    mentions = sum(1 for w in draft_words if w in topic_words)
    return round(mentions / len(draft_words), 4)


def _flesch_kincaid_grade(text: str) -> float:
    """Approximate Flesch-Kincaid Grade Level (code-only, 0 API tokens)."""
    sentences = re.split(r"[.!?]+", text)
    sentences = [s.strip() for s in sentences if len(s.strip()) > 5]
    if not sentences:
        return 0.0
    words = re.findall(r"[a-zA-Z]+", text)
    if not words:
        return 0.0

    def _syllables(w: str) -> int:
        w = w.lower().strip()
        if len(w) <= 3:
            return 1
        if w.endswith("e"):
            w = w[:-1]
        return max(1, len(re.findall(r"[aeiouy]+", w)))

    total_syllables = sum(_syllables(w) for w in words)
    asl = len(words) / len(sentences)
    asw = total_syllables / len(words)
    return round(max(0.0, 0.39 * asl + 11.8 * asw - 15.59), 2)


def _reading_ease(text: str) -> float:
    """Approximate Flesch Reading Ease score."""
    sentences = re.split(r"[.!?]+", text)
    sentences = [s.strip() for s in sentences if len(s.strip()) > 5]
    if not sentences:
        return 0.0
    words = re.findall(r"[a-zA-Z]+", text)
    if not words:
        return 0.0

    def _syllables(w: str) -> int:
        w = w.lower().strip()
        if len(w) <= 3:
            return 1
        if w.endswith("e"):
            w = w[:-1]
        return max(1, len(re.findall(r"[aeiouy]+", w)))

    total_syllables = sum(_syllables(w) for w in words)
    asl = len(words) / len(sentences)
    asw = total_syllables / len(words)
    return round(max(0.0, min(100.0, 206.835 - 1.015 * asl - 84.6 * asw)), 2)


def _semantic_coherence(draft: str) -> float:
    """Compute semantic coherence between consecutive paragraphs using local embeddings.
    
    Returns average pairwise cosine similarity between adjacent paragraphs.
    Higher = more coherent flow.
    """
    try:
        from app.local_semantics import get_embeddings, cosine_similarity
        paragraphs = [p.strip() for p in draft.split("\n\n") if p.strip() and not p.strip().startswith("#")]
        if len(paragraphs) < 2:
            return 1.0  # Single paragraph = fully coherent
        # Take first 300 chars of each paragraph
        texts = [p[:300] for p in paragraphs[:8]]
        embeddings = get_embeddings(texts)
        similarities = []
        for i in range(len(embeddings) - 1):
            sim = cosine_similarity(embeddings[i], embeddings[i + 1])
            similarities.append(float(sim))
        return round(sum(similarities) / len(similarities), 4) if similarities else 0.5
    except Exception as exc:
        logger.debug("Semantic coherence computation failed: %s", exc)
        return 0.5


def _count_nli_contradictions(draft: str, context: str) -> int:
    """Count sentences in the draft that contradict the retrieved context.

    Uses the Local NLI CrossEncoder (DeBERTa-v3-small) to detect hallucinations.
    Returns the number of sentences flagged as contradictions (0 API tokens).
    """
    if not draft or not context:
        return 0
    try:
        from app.local_nli import get_nli_model
        import numpy as np

        model = get_nli_model()
        sentences = re.split(r'(?<=[.!?])\s+', draft[:3000])
        sentences = [s.strip() for s in sentences if len(s.split()) >= 5]
        if not sentences:
            return 0

        contradictions = 0
        context_truncated = context[:4000]
        for sentence in sentences[:20]:  # Cap at 20 sentences for latency
            try:
                scores = model.predict([context_truncated, sentence])
                probs = np.exp(scores) / np.sum(np.exp(scores), axis=-1, keepdims=True)
                prob_contradiction = float(probs[0])
                prob_entailment = float(probs[1])
                if prob_contradiction > 0.60 and prob_entailment < 0.20:
                    contradictions += 1
            except Exception:
                continue
        return contradictions
    except Exception as exc:
        logger.debug("NLI contradiction counting failed: %s", exc)
        return 0


def extract_features(state: dict[str, Any]) -> dict[str, Any]:
    """Extract the ML feature vector from a completed GraphState.

    Parameters
    ----------
    state : dict
        The final GraphState after a complete RAG pipeline run.

    Returns
    -------
    dict
        A flat dictionary of numeric features suitable for ML training.
    """
    draft = state.get("draft", "")
    parsed = state.get("parsed", {})
    retrieved_docs = state.get("retrieved_docs", [])
    retrieval_meta = state.get("retrieval_meta", {})
    topic = parsed.get("topic", "")

    # -- Retrieval features --
    doc_scores = [float(d.get("score", 0)) for d in retrieved_docs]
    semantic_scores = []
    authority_scores = []
    for d in retrieved_docs:
        if "semantic_score" in d:
            semantic_scores.append(float(d["semantic_score"]))
        # Authority score may be in metadata
        auth = d.get("authority_score", d.get("metadata", {}).get("authority_score", 0.5))
        authority_scores.append(float(auth))

    retrieval_score_mean = round(sum(doc_scores) / len(doc_scores), 4) if doc_scores else 0.0
    retrieval_score_max = round(max(doc_scores), 4) if doc_scores else 0.0
    semantic_score_mean = round(sum(semantic_scores) / len(semantic_scores), 4) if semantic_scores else 0.0
    source_authority_mean = round(sum(authority_scores) / len(authority_scores), 4) if authority_scores else 0.0

    # RAG Evaluator dimensions (if available in retrieval_meta)
    rag_eval = retrieval_meta if isinstance(retrieval_meta, dict) else {}

    # -- Draft / Content features --
    word_count = len(draft.split()) if draft else 0
    heading_count = _count_headings(draft)
    fk_grade = _flesch_kincaid_grade(draft) if draft else 0.0
    read_ease = _reading_ease(draft) if draft else 0.0
    kw_density = _keyword_density(draft, topic)

    # -- Pipeline metadata --
    complexity_score_raw = state.get("supervisor_notes", "")
    complexity_match = re.search(r"score=(\d+)", complexity_score_raw)
    complexity_score = int(complexity_match.group(1)) if complexity_match else 0

    # -- Semantic coherence (local embeddings, 0 API tokens) --
    coherence = _semantic_coherence(draft) if draft and word_count > 50 else 0.5

    # -- NLI Contradiction count (local CrossEncoder, 0 API tokens) --
    context_for_nli = "\n".join(d.get("content", "")[:500] for d in retrieved_docs[:5])
    nli_contradictions = _count_nli_contradictions(draft, context_for_nli) if draft and context_for_nli else 0

    features = {
        # Retrieval features
        "retrieval_doc_count": len(retrieved_docs),
        "retrieval_score_mean": retrieval_score_mean,
        "retrieval_score_max": retrieval_score_max,
        "retrieval_semantic_mean": semantic_score_mean,
        "retrieval_relevance": float(rag_eval.get("relevance", 0.0)),
        "retrieval_coverage": float(rag_eval.get("coverage", 0.0)),
        "retrieval_diversity": float(rag_eval.get("diversity", 0.0)),
        "retrieval_freshness": float(rag_eval.get("freshness", 0.0)),
        "source_authority_mean": source_authority_mean,
        # Draft features
        "draft_word_count": word_count,
        "draft_heading_count": heading_count,
        "draft_fk_grade": fk_grade,
        "draft_reading_ease": read_ease,
        "draft_keyword_density": kw_density,
        "semantic_coherence": coherence,
        "nli_contradictions": nli_contradictions,
        # Pipeline features
        "topic_complexity_score": complexity_score,
        "revision_count": int(state.get("revision_count", 0)),
        "retrieval_attempts": int(state.get("retrieval_attempts", 0)),
    }
    return features


