def generate_labels_heuristic(state: dict[str, Any], features: dict[str, Any]) -> dict[str, Any]:
    """Generate quality labels using heuristic rules (zero LLM tokens).

    This is the fallback labeling strategy when no LLM judge is available
    or when we want to label data without API cost.

    Parameters
    ----------
    state : dict
        The final GraphState.
    features : dict
        The extracted feature vector.

    Returns
    -------
    dict
        Label dictionary with faithfulness_score, relevance_score, quality_class.
    """
    draft = state.get("draft", "")

    # Heuristic faithfulness: check if draft mentions "Internal data does not"
    from app.langchain_pipeline import MISSING_INTERNAL_DATA_TEXT
    if MISSING_INTERNAL_DATA_TEXT in draft:
        faithfulness = 1.0  # Perfect refusal
    elif features["retrieval_doc_count"] == 0:
        faithfulness = 0.2  # No docs → likely hallucination
    elif features["retrieval_score_mean"] >= 3.0 and features["retrieval_semantic_mean"] >= 0.3:
        faithfulness = 0.85
    elif features["retrieval_score_mean"] >= 2.0:
        faithfulness = 0.65
    else:
        faithfulness = 0.4

    # Heuristic relevance: based on keyword density + heading structure
    if features["draft_keyword_density"] >= 0.01 and features["draft_heading_count"] >= 2:
        relevance = 0.9
    elif features["draft_keyword_density"] >= 0.005:
        relevance = 0.7
    else:
        relevance = 0.4

    # Quality class derived from combined score
    combined = 0.6 * faithfulness + 0.4 * relevance
    if combined >= 0.75:
        quality_class = "high"
    elif combined >= 0.45:
        quality_class = "medium"
    else:
        quality_class = "low"

    return {
        "faithfulness_score": round(faithfulness, 3),
        "relevance_score": round(relevance, 3),
        "quality_class": quality_class,
        "label_source": "heuristic",
    }


def generate_labels_llm_judge(state: dict[str, Any]) -> dict[str, Any] | None:
    """Generate quality labels using LLM-as-a-judge (costs API tokens).

    Returns None if the LLM is unavailable or fails.
    """
    try:
        from app.langchain_pipeline import pipeline
        from langchain_core.messages import SystemMessage, HumanMessage

        llm = getattr(pipeline, "_editor_llm", None) or pipeline._llm
        if llm is None:
            return None

        draft = state.get("draft", "")
        retrieved_docs = state.get("retrieved_docs", [])
        context = "\n\n".join(d.get("content", "")[:500] for d in retrieved_docs[:5])

        system_prompt = (
            "You are a strict RAG quality evaluator. Score the following blog draft.\n"
            "Return ONLY a valid JSON object with exactly these keys:\n"
            '{"faithfulness": <float 0.0-1.0>, "relevance": <float 0.0-1.0>}\n'
            "faithfulness = how well the draft is grounded in the retrieved context.\n"
            "relevance = how well the draft addresses the user's original topic.\n"
            "Do NOT include newlines or special characters inside field values."
        )
        user_prompt = (
            f"### Retrieved Context:\n{context[:3000]}\n\n"
            f"### Generated Draft:\n{draft[:2000]}"
        )

        response = llm.invoke([
            SystemMessage(content=system_prompt),
            HumanMessage(content=user_prompt),
        ])
        raw = getattr(response, "content", str(response)).strip()

        # Clean markdown fences
        clean = raw.strip()
        if clean.startswith("```"):
            clean = re.sub(r"^```(?:json)?\n?", "", clean)
            clean = re.sub(r"\n?```$", "", clean)
            clean = clean.strip()

        parsed = json.loads(clean)
        faithfulness = min(1.0, max(0.0, float(parsed.get("faithfulness", 0.5))))
        relevance = min(1.0, max(0.0, float(parsed.get("relevance", 0.5))))

        combined = 0.6 * faithfulness + 0.4 * relevance
        if combined >= 0.75:
            quality_class = "high"
        elif combined >= 0.45:
            quality_class = "medium"
        else:
            quality_class = "low"

        return {
            "faithfulness_score": round(faithfulness, 3),
            "relevance_score": round(relevance, 3),
            "quality_class": quality_class,
            "label_source": "llm_judge",
        }
    except Exception as exc:
        logger.warning("LLM-as-judge labeling failed: %s", exc)
        return None


