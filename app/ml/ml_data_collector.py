# Failure Diagnosis (for Dual-Scope Routing)
# ---------------------------------------------------------------------------

def diagnose_failure_source(features: dict[str, Any]) -> str:
    """Analyze features to determine if quality failure is due to
    retrieval issues or generation issues.

    Returns
    -------
    str
        'retrieval' — low retrieval quality → route back to Researcher
        'generation' — low draft quality → route back to Writer
        'both' — both retrieval and generation are weak
        'none' — no clear failure detected
    """
    # Retrieval quality indicators
    retrieval_weak = (
        features.get("retrieval_relevance", 0) < 0.4
        or features.get("retrieval_coverage", 0) < 0.4
        or features.get("retrieval_doc_count", 0) < 2
    )

    # Generation quality indicators
    generation_weak = (
        features.get("nli_contradictions", 0) >= 2
        or features.get("draft_fk_grade", 0) > 14
        or features.get("draft_reading_ease", 100) < 30
        or features.get("semantic_coherence", 1) < 0.3
    )

    if retrieval_weak and generation_weak:
        return "both"
    elif retrieval_weak:
        return "retrieval"
    elif generation_weak:
        return "generation"
    return "none"
